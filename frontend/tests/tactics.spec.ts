import { expect, test } from '@playwright/test'

async function settle(page: import('@playwright/test').Page) {
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))))
}

test('real evidence, overlays, moments, clock and cameras stay synchronized',async({page})=>{
  const errors:string[]=[]
  page.on('pageerror',e=>errors.push(e.message))
  page.on('console',m=>{if(m.type()==='error')errors.push(m.text())})
  await page.setViewportSize({width:1440,height:1100})
  await page.goto('/')
  await expect(page.getByTestId('scene-ready')).toHaveAttribute('data-ready','true')
  const canvas=page.locator('canvas')
  const before=await canvas.screenshot()
  await page.getByRole('button',{name:'Analyze this moment'}).click()
  await expect(page.getByTestId('tactical-moment-title')).toHaveText('The initial shape')
  await expect(page.getByTestId('corridor-state')).toContainText('obstructed')
  await settle(page)
  expect(before.equals(await canvas.screenshot())).toBe(false)
  await page.getByTestId('replay-viewport').screenshot({path:'../output/playwright/tactics/00-initial-corridor.png'})
  await page.getByRole('checkbox',{name:'Defensive movement',exact:true}).check()
  await page.getByRole('checkbox',{name:'Space & coverage',exact:true}).check()
  await page.getByRole('checkbox',{name:'Player relationships',exact:true}).check()
  await page.getByRole('button',{name:/Defensive reshaping/}).click()
  await expect(page.getByTestId('replay-time')).toContainText('6.0')
  await page.getByRole('button',{name:'Tactical',exact:true}).click()
  await settle(page)
  await expect(canvas).toHaveAttribute('data-tactical-layers','passing,movement,space,relationships')
  await page.getByTestId('replay-viewport').screenshot({path:'../output/playwright/tactics/06-reshaping-overhead.png'})
  await page.getByRole('combobox',{name:'Player perspective'}).selectOption('pov:d4')
  await expect(page.getByTestId('replay-time')).toContainText('6.0')
  await settle(page)
  await page.getByTestId('replay-viewport').screenshot({path:'../output/playwright/tactics/06-mercer-pov.png'})
  await page.getByRole('button',{name:/The passing corridor/}).click()
  await expect(page.getByTestId('primary-observation')).toContainText('2.70 m')
  await expect(page.getByTestId('corridor-state')).toContainText('clear under geometric thresholds')
  await page.getByRole('button',{name:'Broadcast',exact:true}).click()
  await settle(page)
  await page.screenshot({path:'../output/playwright/tactics/09-pass-studio.png',fullPage:true})
  await page.getByRole('checkbox',{name:'Passing lanes',exact:true}).uncheck()
  await settle(page)
  await expect(canvas).toHaveAttribute('data-tactical-layers','movement,space,relationships')
  const slider=page.getByRole('slider',{name:'Replay timeline'})
  await slider.fill('5')
  await settle(page)
  await page.getByTestId('replay-viewport').screenshot({path:'../output/playwright/tactics/05-diagonal-run.png'})
  await slider.fill('3')
  await expect(page.getByTestId('tactical-moment-title')).toHaveText('Rowan’s diagonal run')
  await page.getByRole('combobox',{name:'Playback speed'}).selectOption('2')
  await page.getByRole('button',{name:'Play replay',exact:true}).click()
  await expect.poll(async()=>Number(await slider.inputValue())).toBeGreaterThan(3.5)
  await page.getByRole('button',{name:'Pause replay',exact:true}).click()
  const t=await slider.inputValue()
  await page.getByRole('button',{name:'Return to replay'}).click()
  await expect(canvas).toHaveAttribute('data-tactical-layers','')
  expect(await slider.inputValue()).toBe(t)
  await page.getByRole('button',{name:'Analyze this moment'}).click()
  await expect(page.getByTestId('tactical-moment-title')).toBeVisible()
  await page.getByRole('region',{name:'Tactical analysis'}).getByRole('button',{name:/The finish/}).click()
  await page.getByRole('checkbox',{name:'Passing lanes',exact:true}).check()
  await page.getByRole('button',{name:'Tactical',exact:true}).click()
  await settle(page)
  await page.getByTestId('replay-viewport').screenshot({path:'../output/playwright/tactics/14-finish.png'})
  expect(await page.locator('canvas').count()).toBe(1)
  expect(errors).toEqual([])
})

test('evidence request failure and source mismatch are explicit and replay survives',async({page})=>{
  await page.route('**/api/scenarios/*/evidence',route=>route.fulfill({status:503,body:'unavailable'}))
  await page.goto('/')
  await page.getByRole('button',{name:'Analyze this moment'}).click()
  await expect(page.getByRole('alert')).toContainText('503')
  await page.getByRole('button',{name:'Play replay',exact:true}).click()
  await expect.poll(async()=>parseFloat(await page.getByTestId('replay-time').innerText())).toBeGreaterThan(.4)
  await page.getByRole('button',{name:'Pause replay',exact:true}).click()
  await page.unroute('**/api/scenarios/*/evidence')
  await page.route('**/api/scenarios/*/evidence',async route=>{
    const response=await route.fetch(),body=await response.json()
    body.sourceHash='stale'
    await route.fulfill({response,json:body})
  })
  await page.getByRole('button',{name:'Retry evidence'}).click()
  await expect(page.getByRole('alert')).toContainText('does not match')
  await page.unroute('**/api/scenarios/*/evidence')
  await page.getByRole('button',{name:'Retry evidence'}).click()
  await expect(page.getByTestId('tactical-moment-title')).toBeVisible()
})

