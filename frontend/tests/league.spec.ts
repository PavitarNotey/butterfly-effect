  await expect(page.getByTestId('strip-fixture')).toHaveCount(5)
  await expect(page.getByRole('heading', { name: 'The pass that wasn’t touched.' })).toBeVisible()
  await expect(page.locator('canvas')).toHaveCount(0)
  await page.getByTestId('strip-fixture').filter({ hasText: 'MATCH OF THE WEEK' }).click()
