  await expect(page.getByTestId('match-final-score')).toHaveText('2 – 1')
  await expect(page.getByRole('heading', { name: 'Vesper Athletic', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Tidal Rovers', exact: true })).toBeVisible()
  await expect(page.getByTestId('replay-event')).toContainText('Kian Merrick')
  await expect(page.getByTestId('replay-event')).toContainText('67′')
  await expect(page.getByTestId('informational-event').locator('a,button')).toHaveCount(0)
  await expect(page.locator('canvas')).toHaveCount(1)
  await expect(page.getByTestId('match-viewer')).toHaveAttribute('data-scenario', 'the-untouched-pass')
  await expect(page.getByTestId('scene-ready')).toHaveAttribute('data-ready', 'true')
  await page.getByRole('button', { name: 'Play preview' }).click()
  await expect.poll(async () => parseFloat(await page.getByTestId('preview-time').innerText())).toBeGreaterThan(.3)
  await page.getByRole('button', { name: 'Pause preview' }).click()
  await page.getByRole('slider', { name: 'Replay timeline' }).fill('6.65')
  await expect(page.getByTestId('preview-time')).toContainText('6.7 / 13.6')
  await page.getByRole('button', { name: 'Overview', exact: true }).click()
  await expect(page.getByTestId('match-viewer')).toHaveAttribute('data-camera', 'overview')
  await page.getByRole('button', { name: 'Restart preview' }).click()
  await expect(page.getByTestId('preview-time')).toHaveText('0.0 / 13.6 s')
  await page.getByTestId('replay-event').getByRole('link').click()
  await expect(page).toHaveURL('/matches/vesper-tidal/moments/vesper-tidal-merrick')
  await expect(page.getByRole('heading', { name: "The Pass That Wasn't Touched." })).toBeVisible()
  await expect(page.getByTestId('replay-time')).toContainText('3.8')
  await expect(page.locator('canvas')).toHaveCount(1)
  await expect(page.getByTestId('replay-viewport')).toHaveAttribute('data-camera', 'broadcast')
  await page.getByRole('button', { name: 'Analyze this moment', exact: true }).click()
