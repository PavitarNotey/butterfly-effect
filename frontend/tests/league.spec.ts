test('API failures and malformed data remain retryable without invented results', async ({ page }) => {
  await page.route('**/api/league', route => route.abort())
  await page.goto('/')
  await expect(page.getByRole('main').getByRole('alert')).toContainText('Check the API connection')
  await expect(page.getByTestId('strip-fixture')).toHaveCount(0)
  await page.unroute('**/api/league')
  await page.getByRole('button', { name: 'Retry connection' }).click()
  await expect(page.getByTestId('strip-fixture')).toHaveCount(5)
  await page.route('**/api/matches/vesper-tidal', route => route.fulfill({ json: { id: 'vesper-tidal', score: { home: 99, away: 0 } } }))
  await page.getByRole('link', { name: 'Explore the match →' }).click()
  await expect(page.getByRole('alert')).toContainText('could not be verified')
  await expect(page.locator('canvas')).toHaveCount(0)
  await page.unroute('**/api/matches/vesper-tidal')
  await page.getByRole('button', { name: 'Retry connection' }).click()
  await expect(page.getByTestId('match-final-score')).toHaveText('2 – 1')
})

test('delayed route responses never replace a newer match', async ({ page }) => {
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/api/matches/vesper-tidal', async route => { await gate; await route.continue().catch(() => {}) })
  await page.goto('/')
  await page.getByRole('link', { name: 'Explore the match →' }).click()
  await expect(page.getByRole('status')).toContainText('Opening the Match Center')
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Fixtures & results' }).click()
  await page.getByRole('link', { name: 'Aurora FC 2 – 1 Boreal Athletic', exact: true }).click()
  await expect(page.getByTestId('match-final-score')).toHaveText('2 – 1')
  release()
  await expect(page.getByTestId('match-viewer')).toHaveAttribute('data-scenario', 'the-invisible-run')
  await expect(page.getByRole('heading', { name: 'Aurora FC', exact: true })).toBeVisible()
})

