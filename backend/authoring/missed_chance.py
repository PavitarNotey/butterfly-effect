def retime(time):
    for (a, c), (b, d) in pairwise(TIME_MAP):
        if time <= b:
            return round(c + (time - a) / (b - a) * (d - c), 6)
    return DURATION


def revision(source):
    s = copy.deepcopy(source)
    s["duration"] = DURATION
    # Keep the ledger's existing 3675.72s miss and minute 62 exactly.
    s["matchStartSeconds"] = 3667.35
    for p in s["players"]:
        route = [(retime(t), x, z) for t, x, z in ROUTES[p["id"]]]
        times = sorted(
            {round(i * 0.1, 6) for i in range(121)}
            | {r[0] for r in route}
            | set(EVENT_TIMES.values())
        )
        p["positions"] = [
            {
                "t": t,
                "position": [
                    round(sample_route(route, t)[0], 6),
                    0,
                    round(sample_route(route, t)[1], 6),
                ],
            }
            for t in times
        ]
        p["facing"] = [{"t": retime(t), "yaw": yaw} for t, yaw in FACINGS[p["id"]]]
    ball = [{"t": retime(k["t"]), "position": k["position"]} for k in BALL]
    for start, end, owner in [(0, 3.55, "s8"), (4.75, 7.65, "s9")]:
        keys = next(p["positions"] for p in s["players"] if p["id"] == owner)
        ball = [k for k in ball if not start <= k["t"] <= end]
        ball += [
            {
                "t": k["t"],
                "position": [round(k["position"][0] + 0.65, 6), 0.16, k["position"][2]],
            }
            for k in keys
            if start <= k["t"] <= end
        ]
    s["ball"] = sorted(ball, key=lambda k: k["t"])
    s["possession"] = [
        {"t": 0, "playerId": "s8"},
        {"t": 3.55, "playerId": None},
        {"t": 4.75, "playerId": "s9"},
        {"t": 7.65, "playerId": None},
    ]
    for e in s["events"]:
        e["t"] = EVENT_TIMES[e["id"]]
    return s


